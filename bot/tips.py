def get_tips_for_duration(minutes: int) -> list[tuple[int, str]]:
    """Get all tip milestones that should have been triggered by now."""
    return [(tip[0], tip[1]) for tip in TIPS if tip[0] <= minutes]


def get_next_tip(minutes: int) -> tuple[int, str, str, str] | None:
    """Get the next upcoming tip milestone."""
    for m, emoji, title, body in TIPS:
        if m > minutes:
            return (m, emoji, title, body)
    return None


def get_tip_at(minutes: int) -> tuple[int, str, str, str] | None:
    """Get the tip closest to (but not past) the given minutes."""
    found = None
    for tip in TIPS:
        if tip[0] <= minutes:
            found = tip
    return found


def format_tip(milestone: tuple[int, str, str, str]) -> str:
    """Format a tip as a Telegram message."""
    minutes, emoji, title, body = milestone
    hours = minutes // 60
    time_str = f"{minutes // 60}ч" if minutes < 1440 else f"{minutes // 1440}д {minutes // 60 % 24}ч"

    return (
        f"{emoji} <b>Совет: {title}</b>\n"
        f"<i>⏱ {time_str} голодания</i>\n\n"
        f"{body}"
    )
